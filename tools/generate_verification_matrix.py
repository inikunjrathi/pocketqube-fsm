from __future__ import annotations

import re
import xml.etree.ElementTree as ET
from dataclasses import dataclass
from pathlib import Path

ID_LINE = re.compile(r"^\|\s*(R[A-Z]?-\d+)\s*\|")

@dataclass(frozen=True)
class RequirementRow:
    id: str
    statement: str
    scope: str
    status: str

def parse_requirements_table(text: str) -> list[RequirementRow]:
    rows: list[RequirementRow] = []
    for line in text.splitlines():
        if not ID_LINE.match(line):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        req_id, statement, scope = cells[0], cells[1], cells[2]
        status = cells[7]
        rows.append(RequirementRow(id=req_id, statement=statement, scope=scope, status=status))
    return rows

def find_test_references(req_id: str, tests_dir: Path) -> list[str]:
    pattern = re.compile(rf"\b{re.escape(req_id)}\b")
    return [
        test_file.name
        for test_file in sorted(tests_dir.glob("test_*.py"))
        if pattern.search(test_file.read_text())
    ]

def parse_junit_requirements(xml_path: Path) -> dict[str, bool]:
    tree = ET.parse(xml_path)
    passed: dict[str, bool] = {}
    for testcase in tree.iter("testcase"):
        failed = testcase.find("failure") is not None or testcase.find("error") is not None
        for prop in testcase.iter("property"):
            if prop.get("name") == "requirement":
                req_id = prop.get("value")
                passed[req_id] = passed.get(req_id, True) and not failed
    return passed

def render_matrix_section(
    label: str,
    rows: list[RequirementRow],
    tests_dir: Path,
    junit_results: dict[str, bool] | None = None,
) -> str:
    header = "| ID | Statement | Scope | Doc Status | Test-Referenced | Test File(s) | Marker-Verified |"
    divider = "|---|---|---|---|---|---|---|"
    lines = [f"## {label}", "", header, divider]
    for row in rows:
        refs = find_test_references(row.id, tests_dir)
        referenced = "Yes" if refs else "No"
        files = ", ".join(refs) if refs else "—"
        if junit_results is None or row.id not in junit_results:
            verified = "—"
        else:
            verified = "Yes" if junit_results[row.id] else "No"
        lines.append(
            f"| {row.id} | {row.statement} | {row.scope} | {row.status} "
            f"| {referenced} | {files} | {verified} |"
        )
    return "\n".join(lines)

def render_document(
    sections: list[tuple[str, list[RequirementRow]]],
    tests_dir: Path,
    junit_results: dict[str, bool] | None = None,
) -> str:
    parts = [
        "<!-- Auto-generated by tools/generate_verification_matrix.py from "
        "docs/requirements/*.md and tests/*.py. Do not hand-edit. -->",
        "",
        "# Verification Matrix",
        "",
        "**Legend (Phase 7A.5 — the two right-hand columns are not "
        "equally strong evidence, and are not meant to be read as such):**",
        "",
        "- **Test-Referenced** is a bare text search: the requirement ID "
        "string appears somewhere in `tests/*.py` (a docstring, a comment, "
        "an assertion message). It confirms the ID was *mentioned*, not "
        "that any test actually exercises or asserts the requirement's "
        "behavior. A `Yes` here alone should not be read as \"verified.\"",
        "- **Marker-Verified** is the real signal: whether every test "
        "case tagged `@pytest.mark.requirement(\"R-xx\")` (recorded into "
        "JUnit XML by `tests/conftest.py`'s collection hook) passed. This "
        "is actual executed, pass/fail evidence for that requirement. "
        "`—` means no marker-tagged test exists yet for that ID, an "
        "honest gap rather than a failure — most requirements tied to a "
        "specific transition row are covered automatically by "
        "`tests/test_transition_coverage.py`'s systematic parametrization; "
        "requirements about engine-wide properties (e.g. R-15, R-16, R-20, "
        "R-26, R-30, R-32) need a deliberately placed marker on the "
        "specific test that verifies them, audited and added where missing "
        "as part of Phase 7A.5.",
        "",
    ]
    for label, rows in sections:
        parts.append(render_matrix_section(label, rows, tests_dir, junit_results))
        parts.append("")
    return "\n".join(parts)

def _label_for(req_path: Path) -> str:
    config_id = req_path.stem.removeprefix("requirements-config-")
    return f"Config {config_id.upper()}"

def main() -> None:
    repo_root = Path(__file__).resolve().parents[1]
    req_dir = repo_root / "docs" / "requirements"
    tests_dir = repo_root / "tests"
    junit_path = repo_root / "build" / "junit.xml"
    junit_results = parse_junit_requirements(junit_path) if junit_path.exists() else None
    sections = [
        (_label_for(req_path), parse_requirements_table(req_path.read_text()))
        for req_path in sorted(req_dir.glob("requirements-config-*.md"))
    ]
    out_path = repo_root / "docs" / "verification-matrix.md"
    out_path.write_text(render_document(sections, tests_dir, junit_results))
    print(f"wrote {out_path}")

if __name__ == "__main__":
    main()
