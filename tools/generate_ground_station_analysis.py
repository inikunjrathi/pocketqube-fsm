from __future__ import annotations

import dataclasses
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from engine.config_loader import Config, load_config  # noqa: E402
from sim.data_arrival import generate_arrivals  # noqa: E402
from sim.driver import run_simulation  # noqa: E402
from sim.metrics import compute_metrics  # noqa: E402
from sim.scenario import GROUND_STATIONS_DUAL  # noqa: E402
from tools.generate_baseline_results import (  # noqa: E402
    DEFAULT_DT_S,
    DEFAULT_DURATION_S,
    DEFAULT_SEED,
    TTC_CLASS_NAME,
)

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT_PATH = REPO_ROOT / "docs" / "ground-station-coverage-analysis.md"

CONFIG_PATHS: tuple[tuple[str, Path], ...] = (
    ("config-a", REPO_ROOT / "config" / "config-a.yaml"),
    ("config-b", REPO_ROOT / "config" / "config-b.yaml"),
    ("config-c", REPO_ROOT / "config" / "config-c.yaml"),
)

@dataclasses.dataclass(frozen=True)
class CoverageRow:
    config_id: str
    station_count: int
    contact_time_s: float
    contact_time_pct: float
    delivery_success_rate: float
    ttc_latency_p95_s: float | None
    energy_per_delivered_bit_j: float | None
    deadline_success_ratio: float = 0.0

def run_coverage_scenario(
    cfg: Config,
    *,
    seed: int,
    duration_s: float,
    dt_s: float,
    ground_stations: tuple[tuple[float, float, float], ...] | None,
) -> CoverageRow:
    contact_ticks = 0

    def _hook(t: float, snapshot: dict) -> None:
        nonlocal contact_ticks
        if snapshot["link_is_up"]:
            contact_ticks += 1

    result = run_simulation(
        cfg, duration_s=duration_s, dt_s=dt_s, seed=seed,
        ground_stations=ground_stations, tick_hook=_hook,
    )

    priority_order = list(cfg.data_class_priority)
    arrivals = generate_arrivals(priority_order, duration_s, seed)
    size_bytes_by_item = {item.id: item.size_bytes for _, item in arrivals}
    metrics = compute_metrics(
        result.deliveries,
        ttc_class_name=TTC_CLASS_NAME,
        priority_order=priority_order,
        size_bytes_by_item=size_bytes_by_item,
    )

    contact_time_s = contact_ticks * dt_s
    return CoverageRow(
        config_id=cfg.config_id,
        station_count=1 if ground_stations is None else len(ground_stations),
        contact_time_s=contact_time_s,
        contact_time_pct=100.0 * contact_time_s / duration_s,
        delivery_success_rate=metrics.delivery_success_rate,
        ttc_latency_p95_s=metrics.ttc_latency_p95_s,
        energy_per_delivered_bit_j=metrics.energy_per_delivered_bit_j,
        deadline_success_ratio=metrics.deadline_success_ratio,
    )

def _fmt_energy(value: float | None) -> str:
    return "—" if value is None else f"{value:.6g}"

def _fmt_s(value: float | None) -> str:
    return "—" if value is None else f"{value:.2f}"

def _render_config_section(config_id: str, rows: tuple[CoverageRow, CoverageRow]) -> str:
    single, dual = rows
    lines = [
        f"## {config_id}",
        "",
        "| Stations | Contact time (s) | Contact time (% of run) | "
        "Delivery success rate | Deadline success ratio | TT&C latency p95 (s) | "
        "Energy per delivered bit (J/bit) |",
        "|---|---|---|---|---|---|---|",
    ]
    for row in (single, dual):
        lines.append(
            f"| {row.station_count} | {row.contact_time_s:,.0f} | "
            f"{row.contact_time_pct:.2f}% | {row.delivery_success_rate * 100:.2f}% | "
            f"{row.deadline_success_ratio * 100:.2f}% | "
            f"{_fmt_s(row.ttc_latency_p95_s)} | {_fmt_energy(row.energy_per_delivered_bit_j)} |"
        )
    lines.append("")

    contact_delta_pct = (
        100.0 * (dual.contact_time_s - single.contact_time_s) / single.contact_time_s
        if single.contact_time_s > 0
        else float("inf")
    )
    delivery_delta_pp = (dual.delivery_success_rate - single.delivery_success_rate) * 100.0
    lines.append(
        f"Adding the second station increases contact time by "
        f"{contact_delta_pct:.1f}% and changes delivery success rate by "
        f"{delivery_delta_pp:+.2f} percentage points for {config_id}."
    )
    lines.append("")
    return "\n".join(lines)

def render_document(rows_by_config: dict[str, tuple[CoverageRow, CoverageRow]]) -> str:
    parts = [
        "<!-- Auto-generated by tools/generate_ground_station_analysis.py. "
        "Do not hand-edit. -->",
        "",
        "# Ground-Station Coverage Analysis",
        "",
        "Phase 7B.1: does adding a second ground station change this "
        "project's generality conclusions? The single-station row below is "
        "the existing reference scenario (Mumbai, sim.scenario's "
        "GROUND_STATION_LAT_DEG/LON_DEG/ALT_M) -- identical to what "
        "docs/baseline-results.md reports. The dual-station row adds a "
        "second, illustrative real-world polar ground station (Svalbard, "
        "78.23N 15.39E -- sim.scenario.GROUND_STATIONS_DUAL; a real "
        "well-known site chosen for a near-polar orbit's genuine per-orbit "
        "visibility, NOT a claim about POQUITO's actual ground segment, "
        "which this project has no citation for beyond the single Mumbai "
        "station). This analysis is purely additive -- it does not change "
        "docs/baseline-results.md or any other single-station result.",
        "",
        "Contact is elevation-gated: the link is up iff elevation >= the "
        "config's minimum elevation (sim/link.py), so this is an "
        "elevation-gated capacity model, not an RF link budget. "
        "Deadline success ratio = items delivered by their deadline / "
        "items generated (sim.metrics). Config C's reference scenario is "
        "the dual-station one (docs/baseline-results.md).",
        "",
    ]
    for config_id, rows in rows_by_config.items():
        parts.append(_render_config_section(config_id, rows))

    parts.append("## Interpretation")
    parts.append("")
    parts.append(
        "A second, geographically distant ground station can only add "
        "contact opportunities (never remove them -- see "
        "tests/test_orbit.py's `test_find_passes_with_second_station_has_"
        "at_least_as_much_contact`), so the honest question is how much it "
        "matters for this mission's actual reported metrics, not whether "
        "it helps at all."
    )
    parts.append("")
    return "\n".join(parts)

def write_ground_station_analysis(
    output_path: str | Path = DEFAULT_OUTPUT_PATH,
    *,
    seed: int = DEFAULT_SEED,
    duration_s: float = DEFAULT_DURATION_S,
    dt_s: float = DEFAULT_DT_S,
) -> None:
    rows_by_config: dict[str, tuple[CoverageRow, CoverageRow]] = {}
    for config_id, config_path in CONFIG_PATHS:
        cfg = load_config(config_path)
        single = run_coverage_scenario(
            cfg, seed=seed, duration_s=duration_s, dt_s=dt_s, ground_stations=None,
        )
        dual = run_coverage_scenario(
            cfg, seed=seed, duration_s=duration_s, dt_s=dt_s,
            ground_stations=GROUND_STATIONS_DUAL,
        )
        rows_by_config[config_id] = (single, dual)
    Path(output_path).write_text(render_document(rows_by_config))

def main() -> None:
    write_ground_station_analysis(DEFAULT_OUTPUT_PATH)
    print(f"wrote {DEFAULT_OUTPUT_PATH}")

if __name__ == "__main__":
    main()
