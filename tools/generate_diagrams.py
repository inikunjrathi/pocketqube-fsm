from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from engine.config_loader import Config, TransitionDef, load_config

ANY_NODE = "ANY"
RELOAD_NODE = "RELOAD"

def sanitize_id(raw_id: str) -> str:
    return raw_id.replace("-", "_")

def _uses_wildcard(cfg: Config) -> bool:
    return any(t.from_states == "*" for t in cfg.transitions)

def _uses_reload(cfg: Config) -> bool:
    return any(t.to == "reload_from_persistence" for t in cfg.transitions)

def _state_declarations(cfg: Config) -> list[str]:
    lines = [f'    state "{s.name}" as {sanitize_id(s.id)}' for s in cfg.states.values()]
    if _uses_wildcard(cfg):
        lines.append(f'    state "(any state)" as {ANY_NODE}')
    if _uses_reload(cfg):
        lines.append(f'    state "(restored from persistence)" as {RELOAD_NODE}')
    return lines

def _target_id(t: TransitionDef, from_id: str) -> str:
    if t.to is None:
        return from_id
    if t.to == "reload_from_persistence":
        return RELOAD_NODE
    return sanitize_id(t.to)

def _transition_edges(cfg: Config) -> list[str]:
    lines = []
    for t in cfg.transitions:
        event_name = cfg.events[t.event].name
        label = f"{t.id} / {event_name}"
        from_ids = [ANY_NODE] if t.from_states == "*" else [sanitize_id(s) for s in t.from_states]
        for from_id in from_ids:
            to_id = _target_id(t, from_id)
            lines.append(f"    {from_id} --> {to_id} : {label}")
    return lines

def render_mermaid_block(cfg: Config) -> str:
    initial_id = sanitize_id(cfg.initial_state)
    lines = ["stateDiagram-v2", f"    [*] --> {initial_id}"]
    lines += _state_declarations(cfg)
    lines += _transition_edges(cfg)
    return "\n".join(lines)

def render_legend_table(cfg: Config) -> str:
    header = "| ID | From | Event | Guard | To | Actions | Requirements |"
    divider = "|---|---|---|---|---|---|---|"
    rows = [header, divider]
    for t in cfg.transitions:
        from_str = "*" if t.from_states == "*" else ", ".join(t.from_states)
        event_name = cfg.events[t.event].name
        guard_str = t.guard if t.guard else "—"
        to_str = t.to if t.to is not None else "(no-op)"
        actions_str = ", ".join(t.actions) if t.actions else "—"
        reqs_str = ", ".join(t.requirements) if t.requirements else "—"
        rows.append(
            f"| {t.id} | {from_str} | {t.event} ({event_name}) | {guard_str} "
            f"| {to_str} | {actions_str} | {reqs_str} |"
        )
    return "\n".join(rows)

def render_diagram_doc(cfg: Config) -> str:
    return (
        f"<!-- Auto-generated by tools/generate_diagrams.py from "
        f"config/{cfg.config_id}.yaml. Do not hand-edit. -->\n\n"
        f"# {cfg.name} — State Diagram\n\n"
        f"```mermaid\n{render_mermaid_block(cfg)}\n```\n\n"
        f"## Transition legend\n\n{render_legend_table(cfg)}\n"
    )

def main() -> None:
    repo_root = Path(__file__).resolve().parents[1]
    config_dir = repo_root / "config"
    out_dir = repo_root / "docs" / "state-machine"
    for config_path in sorted(config_dir.glob("*.yaml")):
        cfg = load_config(config_path)
        out_path = out_dir / f"{cfg.config_id}-diagram.md"
        out_path.write_text(render_diagram_doc(cfg))
        print(f"wrote {out_path}")

if __name__ == "__main__":
    main()
