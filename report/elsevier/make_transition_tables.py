import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).with_name("transitions.tex")

def tex(s):
    return str(s).replace("_", r"\_\allowbreak ")

def states_span(ids, all_ids):
    if ids == ["*"]:
        return "any"
    idx = [all_ids.index(i) for i in ids]
    if len(ids) > 2 and idx == list(range(idx[0], idx[-1] + 1)):
        return f"{ids[0]}..{ids[-1]}"
    return ", ".join(ids)

def guard(g):
    if not g:
        return "--"
    g = re.sub(r"\s+", " ", g)
    return r"\texttt{" + tex(g).replace(">=", r"$\geq$").replace("<=", r"$\leq$").replace("<", "$<$").replace(">", "$>$") + "}"

def target(t):
    return {None: "(self)", "reload_from_persistence": "reload"}.get(t, t)

parts = []
for c in "abc":
    d = yaml.safe_load((ROOT / f"config/config-{c}.yaml").read_text())
    sids = [s["id"] for s in d["states"]]
    ev = {e["id"]: e["name"] for e in d["events"]}
    rows = [
        f"{t['id']} & {states_span(t['from'] if isinstance(t['from'], list) else [t['from']], sids)} & "
        f"{tex(ev[t['event']])} & {guard(t.get('guard'))} & {target(t['to'])} & {', '.join(chr(92) + 'mbox{' + r + '}' for r in t['requirements'])} \\\\"
        for t in d["transitions"]
    ]
    parts.append(
        f"\\Needspace{{12\\baselineskip}}\n\\subsection{{Config {c.upper()} ({len(rows)} transitions)}}\\label{{app:trans-{c}}}\n"
        "{\\scriptsize\n\\begin{longtable}{@{}p{0.05\\textwidth}p{0.11\\textwidth}p{0.25\\textwidth}p{0.25\\textwidth}p{0.06\\textwidth}p{0.10\\textwidth}@{}}\n"
        f"\\caption{{Config {c.upper()} transition table, generated from \\texttt{{config/config-{c}.yaml}}.}}\\\\\n"
        "\\toprule\nID & From & Event & Guard & To & Req. \\\\\n\\midrule\n\\endfirsthead\n"
        "\\toprule\nID & From & Event & Guard & To & Req. \\\\\n\\midrule\n\\endhead\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{longtable}}\n"
    )
OUT.write_text("% Generated by make_transition_tables.py. Do not hand-edit.\n" + "\n".join(parts))
print(f"wrote {OUT}")
