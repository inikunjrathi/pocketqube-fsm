import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).with_name("timings.tex")

def same_as_head(doc):
    head = subprocess.run(["git", "show", f"HEAD:docs/{doc}"], cwd=ROOT, capture_output=True, text=True, check=True).stdout
    return head == (ROOT / "docs" / doc).read_text()

def outcome(doc):
    return "Identical to committed results" if same_as_head(doc) else "Changed; see Section~\\ref{sec:rerun}"

text = (ROOT / "docs/policy-complexity-analysis.md").read_text()
section_a = text.split("## Config config-a")[1].split("## Config")[0]
rows = {}
for line in section_a.splitlines():
    cells = [c.strip() for c in line.strip("|").split("|")]
    if cells and cells[0] in ("baseline", "tree", "oracle"):
        rows[cells[0]] = (cells[2], cells[3])
ratio = re.search(r"~([\d,]+)x the tree", section_a).group(1)

def tex_time(v):
    return v.replace("µs", r"\textmu s")

cport = Path(sys.argv[1]).read_text()
m1 = re.search(r"calls=(\d+) legal=(\d+) illegal=(\d+) firmware_vs_oracle_mismatches=(\d+)", cport)
m2 = re.search(r"fresh capture: calls=(\d+) entries_differing_from_archive=(\d+)", cport)
cport_text = (
    f"Firmware not rebuilt (no Zephyr SDK on the re-run host); archived firmware log vs.\\ archived Python log: "
    f"{int(m1.group(1)):,} calls, {m1.group(4)} mismatches; fresh Python capture: {int(m2.group(1)):,} calls, "
    f"{m2.group(2)} entries differing from the archive"
)

macros = {
    "TimeBaseMean": tex_time(rows["baseline"][0]), "TimeBaseStd": tex_time(rows["baseline"][1]),
    "TimeTreeMean": tex_time(rows["tree"][0]), "TimeTreeStd": tex_time(rows["tree"][1]),
    "TimeOracleMean": tex_time(rows["oracle"][0]), "TimeOracleStd": tex_time(rows["oracle"][1]),
    "TimeRatio": ratio.replace(",", "{,}"),
    "RerunPolicy": outcome("policy-comparison-results.md"),
    "RerunSensitivity": outcome("sensitivity-analysis.md"),
    "RerunGround": outcome("ground-station-coverage-analysis.md"),
    "RerunWorst": outcome("worst-case-scenario-analysis.md"),
    "RerunCport": cport_text,
}
OUT.write_text("% Generated by fill_rerun_macros.py. Do not hand-edit.\n"
               + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in macros.items()))
for k, v in macros.items():
    print(f"{k}: {v}")
