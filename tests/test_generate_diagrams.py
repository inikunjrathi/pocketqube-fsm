from __future__ import annotations

import subprocess
import sys
from pathlib import Path

from engine.config_loader import load_config
from tools.generate_diagrams import (
    render_diagram_doc,
    render_legend_table,
    render_mermaid_block,
    sanitize_id,
)

REPO_ROOT = Path(__file__).resolve().parents[1]
CONFIG_A = load_config(REPO_ROOT / "config" / "config-a.yaml")
CONFIG_B = load_config(REPO_ROOT / "config" / "config-b.yaml")

def test_sanitize_id_replaces_hyphens():
    assert sanitize_id("S-01") == "S_01"
    assert sanitize_id("T-22") == "T_22"

def test_mermaid_block_contains_every_state_id_config_a():
    block = render_mermaid_block(CONFIG_A)
    for state_id in CONFIG_A.states:
        assert sanitize_id(state_id) in block

def test_mermaid_block_contains_every_state_id_config_b():
    block = render_mermaid_block(CONFIG_B)
    for state_id in CONFIG_B.states:
        assert sanitize_id(state_id) in block

def test_legend_has_one_row_per_transition_config_a():
    table = render_legend_table(CONFIG_A)
    data_rows = [line for line in table.splitlines() if line.startswith("| T-")]
    assert len(data_rows) == len(CONFIG_A.transitions)

def test_legend_has_one_row_per_transition_config_b():
    table = render_legend_table(CONFIG_B)
    data_rows = [line for line in table.splitlines() if line.startswith("| T-")]
    assert len(data_rows) == len(CONFIG_B.transitions)

def test_wildcard_reset_transition_targets_reload_node_config_a():
    block = render_mermaid_block(CONFIG_A)
    assert "ANY --> RELOAD : T-22 / RESET" in block

def test_wildcard_noop_transition_is_self_loop_on_any_config_a():
    block = render_mermaid_block(CONFIG_A)
    assert "ANY --> ANY : T-23 / UPLINK_CMD_GENERIC" in block

def test_wildcard_reset_transition_targets_reload_node_config_b():
    block = render_mermaid_block(CONFIG_B)
    assert "ANY --> RELOAD : T-13 / RESET" in block

def test_wildcard_noop_transition_is_self_loop_on_any_config_b():
    block = render_mermaid_block(CONFIG_B)
    assert "ANY --> ANY : T-14 / UPLINK_CMD_GENERIC" in block

def test_diagram_doc_includes_mermaid_fence_and_legend_heading():
    doc = render_diagram_doc(CONFIG_A)
    assert "```mermaid" in doc
    assert "## Transition legend" in doc
    assert "Auto-generated by tools/generate_diagrams.py" in doc

def test_runs_as_a_direct_script_not_only_as_a_module():
    result = subprocess.run(
        [sys.executable, str(REPO_ROOT / "tools" / "generate_diagrams.py")],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
    )
    assert result.returncode == 0, result.stderr
