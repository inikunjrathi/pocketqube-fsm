REPO_ROOT = Path(__file__).resolve().parents[1]
CONFIG_A = REPO_ROOT / "config" / "config-a.yaml"

SHORT_DURATION_S = 8 * ORBITAL_PERIOD_S
SEED = 42

def test_with_overridden_parameter_replaces_only_the_target():
    cfg = load_config(CONFIG_A)
    original_value = cfg.parameters["P-013"].value

    swept = with_overridden_parameter(cfg, "P-013", 99.0)

    assert swept.parameters["P-013"].value == 99.0
    assert cfg.parameters["P-013"].value == original_value
    for param_id in cfg.parameters:
        if param_id != "P-013":
            assert swept.parameters[param_id].value == cfg.parameters[param_id].value
    assert swept.config_id == cfg.config_id
    assert swept.states == cfg.states

def test_with_overridden_parameter_unknown_id_raises():
    cfg = load_config(CONFIG_A)
    try:
        with_overridden_parameter(cfg, "P-999", 1.0)
        assert False, "expected KeyError"
    except KeyError:
        pass

def test_run_sweep_produces_one_result_per_swept_value():
    cfg = load_config(CONFIG_A)
    spec = SweepSpec(
        "P-015", "link_quality_min_elevation_deg", "deg",
        baseline_value=10.0, low_value=5.0, high_value=15.0,
    )
    results = run_sweep(cfg, spec, seed=SEED, duration_s=SHORT_DURATION_S, dt_s=60.0)

    assert len(results) == 3
    values = {r.value for r in results}
    assert values == {5.0, 10.0, 15.0}
    for r in results:
        assert 0.0 <= r.delivery_success_rate <= 1.0

