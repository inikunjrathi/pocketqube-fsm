def test_overridden_comms_draw_applies_and_restores():
    original = dict(_power_module._COMMS_BURST_DRAW_W_BY_CATEGORY)
    original_sstv = original["COMMS_SSTV"]

    with _overridden_comms_draw("COMMS_SSTV", 999.0):
        assert _power_module._COMMS_BURST_DRAW_W_BY_CATEGORY["COMMS_SSTV"] == 999.0
        assert _power_module._COMMS_BURST_DRAW_W_BY_CATEGORY["COMMS_VOICE"] == original["COMMS_VOICE"]

    assert _power_module._COMMS_BURST_DRAW_W_BY_CATEGORY["COMMS_SSTV"] == original_sstv
    assert _power_module._COMMS_BURST_DRAW_W_BY_CATEGORY == original

def test_overridden_comms_draw_restores_even_on_exception():
    original = dict(_power_module._COMMS_BURST_DRAW_W_BY_CATEGORY)
    try:
        with _overridden_comms_draw("COMMS_SSTV", 999.0):
            raise RuntimeError("boom")
    except RuntimeError:
        pass
    assert _power_module._COMMS_BURST_DRAW_W_BY_CATEGORY == original

def _delivery(item_id, data_class, *, delivered, energy_wh=None):
    return DeliveryRecord(
        item_id=item_id, data_class=data_class, arrival_time_s=0.0,
        delivered=delivered, delivery_time_s=None, latency_s=None,
        deadline_missed=False, energy_wh=energy_wh,
    )

def test_energy_per_bit_by_class_computed_correctly():
    deliveries = [
        _delivery("s1", "SSTV", delivered=True, energy_wh=0.001),
        _delivery("s2", "SSTV", delivered=True, energy_wh=0.002),
        _delivery("t1", "TTC", delivered=True, energy_wh=0.0005),
        _delivery("s3", "SSTV", delivered=False, energy_wh=None),
    ]
    size_bytes_by_item = {"s1": 100, "s2": 200, "t1": 50, "s3": 999}

    result = _energy_per_bit_by_class(deliveries, size_bytes_by_item)

    assert result["SSTV"] == pytest.approx(0.0045)
    assert result["TTC"] == pytest.approx(0.0045)

def test_run_power_uncertainty_sweep_returns_three_ratios():
    cfg = load_config(CONFIG_A)
    results = run_power_uncertainty_sweep(
        cfg, "SSTV", "COMMS_SSTV", 1.5,
        seed=SEED, duration_s=SHORT_DURATION_S, dt_s=60.0,
    )
    assert len(results) == 3
    ratios = [r.ratio for r in results]
    assert ratios[0] < ratios[1] < ratios[2]
    assert ratios[1] == pytest.approx(1.5)

