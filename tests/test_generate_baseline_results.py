from __future__ import annotations

from pathlib import Path

from engine.config_loader import load_config
from sim.metrics import BaselineMetrics
from sim.scenario import GROUND_STATIONS_DUAL, ORBITAL_PERIOD_S
from tools.generate_baseline_results import (
    BaselineRow,
    PerClassBreakdown,
    render_document,
    run_baseline,
    run_baseline_multi_seed,
    write_baseline_results,
)

REPO_ROOT = Path(__file__).resolve().parents[1]
CONFIG_A = REPO_ROOT / "config" / "config-a.yaml"
CONFIG_B = REPO_ROOT / "config" / "config-b.yaml"

SHORT_DURATION_S = 8 * ORBITAL_PERIOD_S
SEED = 42

def _hand_built_rows() -> list[BaselineRow]:
    metrics_a = BaselineMetrics(
        delivery_success_rate=0.75,
        ttc_latency_min_s=1.0,
        ttc_latency_median_s=2.0,
        ttc_latency_p95_s=4.8,
        ttc_latency_max_s=5.0,
        energy_per_delivered_bit_j=0.0045,
        deadline_misses_by_class={"TTC": 0, "SSTV": 1, "CODEC2_M17": 0},
    )
    metrics_b = BaselineMetrics(
        delivery_success_rate=0.0,
        ttc_latency_min_s=None,
        ttc_latency_median_s=None,
        ttc_latency_p95_s=None,
        ttc_latency_max_s=None,
        energy_per_delivered_bit_j=None,
        deadline_misses_by_class={"TTC": 0, "SSTV": 0, "CODEC2_M17": 0},
    )
    breakdown_a = {
        "TTC": PerClassBreakdown(arrived=4, delivered_on_time=3, delivered_late=0, never_delivered=1),
        "SSTV": PerClassBreakdown(arrived=2, delivered_on_time=0, delivered_late=1, never_delivered=1),
        "CODEC2_M17": PerClassBreakdown(arrived=1, delivered_on_time=0, delivered_late=0, never_delivered=1),
    }
    breakdown_b = {
        "TTC": PerClassBreakdown(arrived=0, delivered_on_time=0, delivered_late=0, never_delivered=0),
        "SSTV": PerClassBreakdown(arrived=0, delivered_on_time=0, delivered_late=0, never_delivered=0),
        "CODEC2_M17": PerClassBreakdown(arrived=0, delivered_on_time=0, delivered_late=0, never_delivered=0),
    }
    return [
        BaselineRow(config_id="config-a", metrics=metrics_a, per_class_breakdown=breakdown_a),
        BaselineRow(config_id="config-b", metrics=metrics_b, per_class_breakdown=breakdown_b),
    ]

def test_render_document_contains_required_metrics():
    doc = render_document(_hand_built_rows())

    for config_id in ("config-a", "config-b"):
        assert config_id in doc

    lowered = doc.lower()
    assert "delivery success rate" in lowered
    assert "tt&c latency" in lowered
    assert "min" in lowered
    assert "median" in lowered
    assert "p95" in lowered
    assert "max" in lowered
    assert "energy per delivered bit" in lowered
    assert "deadline misses" in lowered
    assert "TTC" in doc
    assert "SSTV" in doc
    assert "CODEC2_M17" in doc

    assert "—" in doc or "N/A" in doc or "n/a" in lowered

    assert "per-class delivery breakdown" in lowered
    assert "never delivered" in lowered

def test_render_document_has_autogenerated_header():
    doc = render_document(_hand_built_rows())
    assert "Auto-generated by tools/generate_baseline_results.py" in doc
    assert "Do not hand-edit" in doc
    assert doc.lstrip().startswith("<!--")

def test_run_baseline_produces_sane_metrics_for_both_configs():
    for config_path in (CONFIG_A, CONFIG_B):
        cfg = load_config(config_path)
        row = run_baseline(cfg, seed=SEED, duration_s=SHORT_DURATION_S, dt_s=60.0)

        assert row.config_id == cfg.config_id
        m = row.metrics
        assert 0.0 <= m.delivery_success_rate <= 1.0

        for latency in (
            m.ttc_latency_min_s,
            m.ttc_latency_median_s,
            m.ttc_latency_p95_s,
            m.ttc_latency_max_s,
        ):
            assert latency is None or latency >= 0.0

        assert m.energy_per_delivered_bit_j is None or m.energy_per_delivered_bit_j >= 0.0

        assert m.deadline_misses_by_class
        for count in m.deadline_misses_by_class.values():
            assert count >= 0

        assert row.per_class_breakdown
        for data_class, b in row.per_class_breakdown.items():
            assert data_class in cfg.data_class_priority
            assert b.arrived == b.delivered_on_time + b.delivered_late + b.never_delivered

def test_run_baseline_default_ground_stations_matches_pre_phase_d_behavior():
    cfg = load_config(CONFIG_A)
    default_row = run_baseline(cfg, seed=SEED, duration_s=SHORT_DURATION_S, dt_s=60.0)
    explicit_none_row = run_baseline(
        cfg, seed=SEED, duration_s=SHORT_DURATION_S, dt_s=60.0, ground_stations=None,
    )
    assert default_row.metrics == explicit_none_row.metrics

def test_run_baseline_with_dual_ground_stations_differs_from_single():
    cfg = load_config(CONFIG_A)
    single = run_baseline(cfg, seed=SEED, duration_s=SHORT_DURATION_S, dt_s=60.0)
    dual = run_baseline(
        cfg, seed=SEED, duration_s=SHORT_DURATION_S, dt_s=60.0,
        ground_stations=GROUND_STATIONS_DUAL,
    )
    assert dual.metrics.delivery_success_rate >= single.metrics.delivery_success_rate

def test_run_baseline_multi_seed_aggregates_across_seeds():
    cfg = load_config(CONFIG_A)
    agg = run_baseline_multi_seed(
        cfg, seeds=(1, 2, 3), duration_s=SHORT_DURATION_S, dt_s=60.0
    )
    assert agg.n_runs == 3
    assert agg.delivery_success_rate.n == 3
    assert 0.0 <= agg.delivery_success_rate.mean <= 1.0
    assert agg.delivery_success_rate.ci95_low <= agg.delivery_success_rate.mean
    assert agg.delivery_success_rate.ci95_high >= agg.delivery_success_rate.mean

def test_write_baseline_results_includes_multi_seed_section(tmp_path):
    output_path = tmp_path / "baseline-results.md"
    write_baseline_results(
        output_path, seed=SEED, duration_s=SHORT_DURATION_S, dt_s=60.0,
        eval_seeds=(1, 2),
    )
    text = output_path.read_text()
    assert "multi-seed" in text.lower()
    assert "95% CI" in text
    assert "config-a" in text and "config-b" in text

def test_main_writes_deterministic_output(tmp_path):
    out_path_1 = tmp_path / "baseline-results-1.md"
    out_path_2 = tmp_path / "baseline-results-2.md"

    write_baseline_results(
        out_path_1, seed=SEED, duration_s=SHORT_DURATION_S, dt_s=60.0
    )
    write_baseline_results(
        out_path_2, seed=SEED, duration_s=SHORT_DURATION_S, dt_s=60.0
    )

    text_1 = out_path_1.read_text()
    text_2 = out_path_2.read_text()
    assert text_1 == text_2
    assert text_1
