from __future__ import annotations

from pathlib import Path

import pytest

from engine.config_loader import load_config
from policy.base import BASELINE_POLICY, FeatureVector
from policy.tree import TreePolicy, fit
from tools.benchmark_policies import (
    PolicyTiming,
    _CapturingPolicy,
    _summarize_timing,
    benchmark_policies,
    capture_decision_contexts,
    render_document,
)

REPO_ROOT = Path(__file__).resolve().parents[1]
CONFIG_A = REPO_ROOT / "config" / "config-a.yaml"
CONFIG_B = REPO_ROOT / "config" / "config-b.yaml"

def test_capture_decision_contexts_reaches_real_decision_points():
    for config_path in (CONFIG_A, CONFIG_B):
        cfg = load_config(config_path)
        contexts = capture_decision_contexts(cfg, max_contexts=3)
        assert len(contexts) > 0
        assert len(contexts) <= 3
        for features, context in contexts:
            assert context.cfg is cfg

def test_capturing_policy_delegates_and_records():
    capturer = _CapturingPolicy(BASELINE_POLICY)
    cfg = load_config(CONFIG_A)
    contexts = capture_decision_contexts(cfg, max_contexts=1)
    assert contexts

    features, context = contexts[0]
    decision = capturer.decide(features, context)

    assert decision == "serve"
    assert capturer.captured == [(features, context)]

def test_summarize_timing_computes_mean_stdev_min_max():
    timing = _summarize_timing("baseline", "O(1)", [1.0, 2.0, 3.0])
    assert timing.policy_name == "baseline"
    assert timing.big_o == "O(1)"
    assert timing.n_samples == 3
    assert timing.mean_s == 2.0
    assert timing.min_s == 1.0
    assert timing.max_s == 3.0
    assert timing.stdev_s > 0.0

def test_summarize_timing_single_sample_has_zero_stdev():
    timing = _summarize_timing("baseline", "O(1)", [5.0])
    assert timing.stdev_s == 0.0

def _hand_built_timings() -> dict[str, list[PolicyTiming]]:
    return {
        "config-a": [
            PolicyTiming("baseline", "O(1)", 100, 1e-7, 1e-8, 8e-8, 2e-7),
            PolicyTiming("tree", "O(depth)", 100, 1e-6, 1e-7, 8e-7, 2e-6),
            PolicyTiming("oracle", "O(2 * horizon_ticks)", 25, 0.03, 0.005, 0.02, 0.04),
        ],
        "config-b": [],
    }

def test_render_document_contains_required_content():
    doc = render_document(_hand_built_timings())

    assert "R-20" in doc
    assert "config-a" in doc
    assert "config-b" in doc
    assert "baseline" in doc
    assert "tree" in doc
    assert "oracle" in doc
    assert "O(1)" in doc
    assert "O(depth)" in doc
    assert "tree's mean" in doc
    assert "insufficient data" in doc.lower()

def test_render_document_has_autogenerated_header():
    doc = render_document(_hand_built_timings())
    assert "Auto-generated by tools/benchmark_policies.py" in doc
    assert "Do not hand-edit" in doc
    assert doc.lstrip().startswith("<!--")

def _dummy_tree_policy():
    features = FeatureVector(
        battery_soc_pct=50.0, elevation_deg=20.0, is_illuminated=True,
        ttc_queue_depth=1, sstv_queue_depth=0, codec2_m17_queue_depth=0,
        top_class_rank=0, top_class_deadline_slack_s=100.0, ticks_since_last_service=1,
    )
    rows = [(features.as_tuple(), "serve"), (features.as_tuple(), "serve")]
    return TreePolicy(fit(rows))

@pytest.mark.requirement("R-20")
def test_benchmark_policies_analyzes_all_three_under_the_same_input_model():
    # R-20
    cfg = load_config(CONFIG_A)
    tree_policy = _dummy_tree_policy()

    timings = benchmark_policies(cfg, tree_policy)

    assert timings, "expected at least one captured decision point"
    names = {t.policy_name for t in timings}
    assert names == {"baseline", "tree", "oracle"}
    for t in timings:
        assert t.big_o
        assert t.n_samples > 0
        assert t.mean_s >= 0.0
    baseline = next(t for t in timings if t.policy_name == "baseline")
    tree = next(t for t in timings if t.policy_name == "tree")
    assert baseline.n_samples == tree.n_samples
